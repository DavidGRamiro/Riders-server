from django.db import models

from apps.users.models import User


class Route(models.Model):
    id_fk_usuario = models.ForeignKey(
        User,
        on_delete=models.DO_NOTHING,
        null=True,
        blank=True,
        db_column="id_fk_usuario",
        related_name="user_route",
    )
    title = models.CharField(max_length=255, null=False, blank=False, db_comment="Title of route")
    is_ai_generated = models.BooleanField(default=False, db_comment="True if is AI generated")
    path_data = models.TextField(null=False, blank=False, db_comment="Path of route")
    distance_km = models.FloatField(null=False, blank=False, db_comment="Distance km of route")

    class Meta:
        db_table = "routes"
        verbose_name = "Route"
        verbose_name_plural = "Routes"

    def __str__(self) -> str:
        return f"{self.title} - {self.distance_km} km"


class RouteGeneratedByUser(models.Model):
    id_fk_user = models.ForeignKey(User, on_delete=models.CASCADE)
    created_at = models.DateTimeField(auto_now_add=True)
    coords = models.JSONField()
    waypoints = models.JSONField()
    distance_km = models.FloatField()
    route_type = models.CharField()
    saved = models.BooleanField(default=False)
    title = models.CharField(max_length=255, db_comment="Title of route", default="Title of route")
    prompt = models.TextField(db_comment="Prompt of route", default="Prompt of route")
    route_code = models.CharField(max_length=10, db_comment="Code of route", unique=True)
    duration = models.FloatField(null=False, blank=False, db_comment="Duration of route")
    way_points_coords = models.JSONField(null=False, blank=False, db_comment="Waypoints of route")

    class Meta:
        db_table = "route_generated_user"
        verbose_name = "Route generated by user"
        verbose_name_plural = "Routes generated by users"

    def __str__(self):
        return f"Ruta generada por {self.user.username}/{self.created_at}"
